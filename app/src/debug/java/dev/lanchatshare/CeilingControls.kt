package dev.lanchatshare

import android.os.PowerManager
import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.semantics.*
import dev.lanchatshare.connectivity.*
import kotlinx.coroutines.*
import org.json.JSONObject
import java.util.Locale

@Composable internal fun CeilingControls(peer: TrustedPeer?, mb: Int, path: String?, setup: String) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var job by remember { mutableStateOf<Job?>(null) }
    var status by remember { mutableStateOf("") }
    HorizontalDivider()
    Text("Measure link capacity",style=MaterialTheme.typography.titleMedium)
    Text("Choose the same size on both phones. Tap Send here on the sender, then Receive here on the receiver. Each phone measures TCP and pinned TLS using generated bytes.")
    fun start(send: Boolean) {
        val target = peer ?: return
        val radio = radioReading(context,target.id)
        val power = context.getSystemService(PowerManager::class.java)
        status = if (send) "Waiting for the receiver…" else "Connecting…"
        job = scope.launch {
            val results = mutableListOf<String>()
            var screen = power.isInteractive
            try {
                runCeiling(target,send,mb,started = { screen = power.isInteractive }) { rate ->
                    val endScreen = power.isInteractive
                    TransferMeter.saveCeiling(context,JSONObject().put("kind","memory").put("transport",rate.mode)
                        .put("direction",if(send) "send" else "receive").put("sizeBytes",rate.bytes)
                        .put("elapsedMs",rate.nanos / 1e6).put("averageMBps",rate.mbps).put("averageMbitPerSec",8*rate.mbps)
                        .put("testSetup",setup).put("peerId",target.id).put("path",path ?: "unknown").put("frequencyMHz",radio.frequency ?: JSONObject.NULL)
                        .put("linkMbps",radio.mbps ?: JSONObject.NULL).put("rssiDbm",radio.rssi ?: JSONObject.NULL)
                        .put("screenOnStart",screen).put("screenOnEnd",endScreen).put("endedAt",System.currentTimeMillis()))
                    results += "%s %.2f MB/s (%.1f Mbit/s)".format(Locale.US,rate.mode,rate.mbps,rate.mbps*8)
                }
                status = results.joinToString(" · ")
            } catch (e: TimeoutCancellationException) { status = "Timed out. Reconnect and run both phones again." }
            catch (e: CancellationException) { status = "Measurement cancelled"; throw e }
            catch (e: Exception) { status = "Measurement stopped. " + (e.message ?: "Check the connection and the selected phone.") }
            finally { job = null }
        }
    }
    if(job == null) {
        OutlinedButton({ start(true) },enabled=peer != null) { Text("Send here") }
        OutlinedButton({ start(false) },enabled=peer != null) { Text("Receive here") }
    } else TextButton({ job?.cancel() }) { Text("Cancel measurement") }
    if(status.isNotBlank()) Text(status,Modifier.semantics { liveRegion = LiveRegionMode.Polite })
}
